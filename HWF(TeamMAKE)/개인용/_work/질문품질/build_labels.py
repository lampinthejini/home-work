def parse(path: Path, round_: int) -> list[dict]:
    rows, person = [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        head = re.match(r"## (\d+)\. ", line)
        if head:
            person = int(head.group(1))
            continue
        if line.startswith("## 예비"):
            person = None
        m = re.match(r"(\d+)\. \[(\S+)(?: · ([^\]]+))?\] (.+)", line)
        if m and person:
            no, kind, src, text = m.groups()
            rows.append({"id": f"{round_}-p{person}-{no}", "person": person, "kind": KIND[kind],
                         "source": "ai" if (src or "AI").startswith("AI") else "reserve", "text": text.strip()})
    return rows


