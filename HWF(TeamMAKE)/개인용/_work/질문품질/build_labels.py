    rows = parse(SRC / "모의지원_10명_결과.md", 1) + parse(SRC / "모의지원_10명_결과_2회차.md", 2)
    seen, out = set(), []
    for r in rows:
        key = (r["person"], r["text"])
        if key in seen:
            continue
        seen.add(key)
        b, q1, q2, q3, why = LABELS[r["id"]]
        out.append({**r, "b": b, "q1": q1, "q2": q2, "q3": q3, "why": why})
    for sid, person, kind, text, b, q1, q2, q3, why in WRITTEN:
        out.append({"id": sid, "person": person, "kind": kind, "source": "written", "text": text,
                    "b": b, "q1": q1, "q2": q2, "q3": q3, "why": why})
    missing = set(LABELS) - {r["id"] for r in rows}
    if missing:
        sys.exit(f"원본에 없는 id: {sorted(missing)}")
    with open(HERE / "labels.jsonl", "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{len(out)}개 (중복 {len(rows) - (len(out) - len(WRITTEN))}개 뺌)")


